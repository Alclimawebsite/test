def test_rate_limiter_throttles_across_threads():
    rl = RateLimiter(rate=100.0, burst=1)
    t0 = time.monotonic()

    def work():
        for _ in range(5):
            rl.acquire()

    threads = [threading.Thread(target=work) for _ in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert time.monotonic() - t0 >= 0.17  # 20 jetons à 100/s, 1 en rafale -> >= 0,19 s


