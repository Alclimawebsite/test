class FakeResponse:
    def __init__(self, status_code: int = 200, payload=None, headers=None):
        self.status_code = status_code
        self._payload = payload
        self.headers = headers or {}
        self.text = json.dumps(payload) if payload is not None else ""

    def json(self):
        if self._payload is None:
            raise ValueError("pas de JSON")
        return self._payload


def _items(params):
    if params is None:
        return []
    return list(params.items()) if isinstance(params, dict) else list(params)


class FakeSession:
    """Routeur minimal gamma / CLOB / data-api ; enregistre les appels."""

    def __init__(self, events=(), prices=None, books=None, trades=None, script=None):
        self.events = {e["slug"]: e for e in events}
        self.prices = prices or {}      # token -> [(t, p)]
        self.books = books or {}        # token -> payload
        self.trades = trades or {}      # condition_id -> [rows]
        self.script = list(script or [])  # réponses / exceptions imposées, consommées d'abord
        self.calls: list[tuple[str, list]] = []
        self.lock = threading.Lock()

    def count(self, fragment: str) -> int:
        return sum(fragment in url for url, _ in self.calls)

    def get(self, url, params=None, timeout=None):
        with self.lock:
            self.calls.append((url, _items(params)))
            if self.script:
                item = self.script.pop(0)
                if isinstance(item, Exception):
                    raise item
                return item
        p = _items(params)
        d = dict(p)
        if url.endswith("/events"):
            slugs = [v for k, v in p if k == "slug"]
            limit = int(d.get("limit", 20))
            return FakeResponse(200, [self.events[s] for s in slugs if s in self.events][:limit])
        if url.endswith("/prices-history"):
            pts = self.prices.get(d["market"], [])
            a, b = int(d["startTs"]), int(d["endTs"])
            return FakeResponse(200, {"history": [{"t": t, "p": v} for t, v in pts if a <= t <= b]})
        if url.endswith("/book"):
            tok = d["token_id"]
            if tok in self.books:
                return FakeResponse(200, self.books[tok])
            return FakeResponse(404, {"error": "No orderbook exists for the requested token id"})
        if url.endswith("/trades"):
            rows = self.trades.get(d["market"], [])
            off, lim = int(d.get("offset", 0)), int(d["limit"])
            return FakeResponse(200, rows[off : off + lim])
        return FakeResponse(404, {"error": "not found"})


class ExplodingSession:
    """Toute requête échoue : prouve qu'une donnée vient du cache."""

    def __init__(self):
        self.calls = 0

    def get(self, *a, **k):
        self.calls += 1
        raise AssertionError("appel réseau inattendu")


def client_for(session, tmp_path, **kw) -> PolymarketClient:
    kw.setdefault("max_rps", 1000.0)
    kw.setdefault("backoff", 0.0)
    return PolymarketClient(session=session, cache_dir=tmp_path / "pm", **kw)


