def test_up_price_at_staleness():
    idx = pd.to_datetime([ts("2026-09-24 16:44:15"), ts("2026-09-24 16:45:17"), ts("2026-09-24 16:46:16")], unit="s", utc=True)
    h = pd.Series([0.505, 0.545, 0.605], index=idx)
    assert math.isnan(up_price_at(h, pd.Timestamp("2026-09-24 16:44:00", tz=UTC)))  # avant le 1er point
    assert up_price_at(h, pd.Timestamp("2026-09-24 16:45:00", tz=UTC)) == 0.505
    assert up_price_at(h, pd.Timestamp("2026-09-24 16:45:17", tz=UTC)) == 0.545  # point exact inclus
    assert up_price_at(h, pd.Timestamp("2026-09-24 16:49:00", tz=UTC)) == 0.605
    assert math.isnan(up_price_at(h, pd.Timestamp("2026-09-24 16:49:30", tz=UTC)))  # > 3 min
    assert up_price_at(h, pd.Timestamp("2026-09-24 16:55", tz=UTC), max_staleness=pd.Timedelta("10min")) == 0.605
    assert up_price_at(h, pd.Timestamp("2026-09-24 16:45:30")) == 0.545  # naïf = UTC
    assert math.isnan(up_price_at(pd.Series(dtype=float), pd.Timestamp("2026-09-24", tz=UTC)))
    assert up_price_at(h.iloc[::-1], pd.Timestamp("2026-09-24 16:46:30", tz=UTC)) == 0.605  # non trié


