def _history_points(start: int) -> list[tuple[int, float]]:
    """Profil réel : 0,505 avant l'ouverture, puis convergence vers 0 (résolu Down)."""
    before = [(start - 1780 + 60 * i, 0.505) for i in range(29)]
    during = [(start + 17, 0.545), (start + 76, 0.545), (start + 136, 0.605), (start + 314, 0.465),
              (start + 555, 0.145), (start + 735, 0.015), (start + 855, 0.0005), (start + 916, 0.0005)]
    return before + during


