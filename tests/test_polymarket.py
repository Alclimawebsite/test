    assert sess.count("/events") == 1  # un seul appel groupé
    assert [m.resolved_up for m in ms[:6]] == [False, True, False, True, False, True]
    files = list((tmp_path / "pm" / "markets").glob("*.parquet"))
    assert [f.name for f in files] == ["btc_15m_2026-01.parquet"]

    # nouveau client, même cache : seul le marché non résolu est redemandé
    sess2 = FakeSession(events=events)
    c2 = client_for(sess2, tmp_path)
    ms2 = c2.list_updown_markets("btc", "15m", pd.Timestamp("2026-01-15", tz=UTC), pd.Timestamp("2026-01-15 02:00", tz=UTC))
    assert [m.slug for m in ms2] == [m.slug for m in ms]
    assert sess2.count("/events") == 1
    asked = [v for k, v in sess2.calls[0][1] if k == "slug"]
    assert asked == [f"btc-updown-15m-{starts[6]}"]
    cached = ms2[0]
    assert cached.resolved_up is False and cached.fee_schedule["rate"] == 0.07
    assert "description" not in cached.raw  # champs volumineux retirés du cache

    # only_closed
    closed = c2.list_updown_markets(
        "btc", "15m", pd.Timestamp("2026-01-15", tz=UTC), pd.Timestamp("2026-01-15 02:00", tz=UTC), only_closed=True
    )
    assert len(closed) == 7


