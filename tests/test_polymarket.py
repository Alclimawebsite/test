def test_slot_starts_4h_new_york_alignment():
    """Vérifié sur l'API : 4h alignées sur New York (EDT -> 0h/4h… UTC ; EST -> 1h/5h… UTC)."""
    summer = slot_starts("4h", pd.Timestamp("2026-09-25", tz=UTC), pd.Timestamp("2026-09-26", tz=UTC))
    assert [pd.Timestamp(x, unit="s", tz=UTC).hour for x in summer] == [0, 4, 8, 12, 16, 20]
    assert all(x % 14400 == 0 for x in summer)
    winter = slot_starts("4h", pd.Timestamp("2026-01-15", tz=UTC), pd.Timestamp("2026-01-16", tz=UTC))
    assert [pd.Timestamp(x, unit="s", tz=UTC).hour for x in winter] == [1, 5, 9, 13, 17, 21]
    assert 1768438800 in winter  # btc-updown-4h-1768438800 existe (8:00PM-12:00AM ET)
    # passage à l'heure d'été (8 mars 2026) : 00h EST puis 04h EDT
    dst = slot_starts("4h", pd.Timestamp("2026-03-08", tz=UTC), pd.Timestamp("2026-03-09", tz=UTC))
    assert [pd.Timestamp(x, unit="s", tz=UTC).hour for x in dst] == [1, 5, 8, 12, 16, 20]
    for x in summer + winter + dst:
        assert pd.Timestamp(x, unit="s", tz=UTC).tz_convert("America/New_York").hour % 4 == 0


