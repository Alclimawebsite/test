def test_retries_then_success_and_exhaustion(tmp_path):
    start = ts("2026-09-24 16:45")
    sess = FakeSession(
        events=[make_event(REAL_MARKET)],
        script=[FakeResponse(503), requests.ConnectionError("reset"), FakeResponse(429, headers={"Retry-After": "0"})],
    )
    c = client_for(sess, tmp_path, use_cache=False)
    assert c.get_updown_market("btc", "15m", start) is not None
    assert len(sess.calls) == 4
    bad = FakeSession(script=[FakeResponse(500)] * 10)
    c2 = client_for(bad, tmp_path, retries=2, use_cache=False)
    with pytest.raises(PolymarketError):
        c2.get_updown_market("btc", "15m", start)
    assert len(bad.calls) == 3
    # 4xx autre que 404/429 : pas de retentative
    c3 = client_for(FakeSession(script=[FakeResponse(422, {"error": "validation"})]), tmp_path, use_cache=False)
    with pytest.raises(PolymarketError):
        c3.get_updown_market("btc", "15m", start)


def test_list_updown_markets_batches_and_caches_resolved(tmp_path):
    t0 = ts("2026-01-15 00:00")
    starts = [t0 + 900 * i for i in range(8)]
    events = [make_event(make_market(s, state="up" if i % 2 else "down")) for i, s in enumerate(starts[:6])]
    events.append(make_event(make_market(starts[6], state="pending")))  # clos, non résolu
    # starts[7] : créneau inexistant (ancien -> absence confirmée et mise en cache)
    sess = FakeSession(events=events)
    c = client_for(sess, tmp_path)
    ms = c.list_updown_markets("btc", "15m", pd.Timestamp("2026-01-15", tz=UTC), pd.Timestamp("2026-01-15 02:00", tz=UTC))
